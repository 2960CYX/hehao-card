/**
 * 手写笔迹的数据结构。
 *
 * 关键点：x、y、w 全部按签名板的 **宽度** 归一化（不是各按宽/高归一化）。
 * 这样坐标系就和签名板的宽高比无关了 —— 在手机全屏里写的字，
 * 能原样缩放到卡片那一小条签名栏里，不会被压扁。
 */
export interface InkPoint {
  /** 相对签名板宽度的 X（0 ~ 1） */
  x: number
  /** 相对签名板宽度的 Y —— 注意也是除以宽度，所以高板子会大于 1 */
  y: number
  /** 笔画粗细，同样相对宽度 */
  w: number
}

export type InkStroke = InkPoint[]
